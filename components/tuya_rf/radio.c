/* Frequency bank actually written to the chip, defaults to the captured 433.92 MHz one */
static uint8_t s_frequencyBank[CMT2300A_FREQUENCY_BANK_SIZE] = {
    0x42, 0x71, 0xCE, 0x1C, 0x42, 0x5B, 0x1C, 0x1C,
};

/* PA power (CUS_TX8, CUS_TX9), defaults to the captured 433.92 MHz values */
static uint8_t s_txPower[2] = { 0x37, 0x0A };

#define RF_XTAL_HZ 26000000ULL

typedef struct {
    uint32_t min_hz;
    uint32_t max_hz;
    uint8_t  vco_bank;
    uint8_t  divx_code;
    uint8_t  divider;
    uint8_t  tx8;       /* PA power from RFPDK, 0 = use the 433.92 MHz value */
    uint8_t  tx9;
} RF_Band;

/* Table 3 of AN199 (CMT2300A RF frequency calculation guide) */
static const RF_Band s_bands[] = {
    { 126330000, 140000000, 6, 3, 12, 0, 0 },
    { 140000000, 170000000, 1, 3, 12, 0, 0 },
    { 189500000, 210000000, 6, 2,  8, 0, 0 },
    { 210000000, 255000000, 1, 2,  8, 0, 0 },
    { 252670000, 280000000, 6, 5,  6, 0, 0 },
    /* PA values taken from an RFPDK 315 MHz export */
    { 280000000, 340000000, 1, 5,  6, 0x49, 0x12 },
    { 379000000, 420000000, 6, 1,  4, 0, 0 },
    { 420000000, 510000000, 1, 1,  4, 0, 0 },
    { 758000000, 840000000, 6, 0,  2, 0, 0 },
    { 840000000, 1020000000, 1, 0, 2, 0, 0 },
};

/*! ********************************************************
* @name    RF_SetFrequency
* @desc    Calculates the frequency bank for the given carrier
*          frequency, following AN199. The RX LO is placed
*          Fxtal/92 above the carrier, N.K = Flo * DIVIDER / Fxtal,
*          K is truncated like RFPDK does.
*          The new values are written at the next RF_Init.
* @param   freq_hz: carrier frequency in Hz
* @return  0 on success, -1 if the frequency is out of range
* *********************************************************/
int RF_SetFrequency(uint32_t freq_hz)
{
    const RF_Band *band = NULL;
    uint64_t rx, tx;
    uint32_t rx_n, rx_k, tx_n, tx_k;
    uint8_t i;

    for (i = 0; i < sizeof(s_bands)/sizeof(s_bands[0]); i++) {
        if (freq_hz >= s_bands[i].min_hz && freq_hz < s_bands[i].max_hz) {
            band = &s_bands[i];
            break;
        }
    }
    if (freq_hz == 1020000000)
        band = &s_bands[sizeof(s_bands)/sizeof(s_bands[0]) - 1];
    if (band == NULL)
        return -1;

    /* N.K * 2^20, rx uses Flo = Frf + Fxtal/92 */
    rx = (((uint64_t)freq_hz * 92 + RF_XTAL_HZ) * band->divider << 20) / (RF_XTAL_HZ * 92);
    tx = (((uint64_t)freq_hz) * band->divider << 20) / RF_XTAL_HZ;
    rx_n = (uint32_t)(rx >> 20);
    rx_k = (uint32_t)(rx & 0xFFFFF);
    tx_n = (uint32_t)(tx >> 20);
    tx_k = (uint32_t)(tx & 0xFFFFF);

    s_frequencyBank[0] = (uint8_t)rx_n;
    s_frequencyBank[1] = (uint8_t)rx_k;
    s_frequencyBank[2] = (uint8_t)(rx_k >> 8);
    s_frequencyBank[3] = (freq_hz >= 500000000 ? CMT2300A_MASK_FREQ_PALDO_SEL : 0)
                       | (band->divx_code << 4)
                       | (uint8_t)(rx_k >> 16);
    s_frequencyBank[4] = (uint8_t)tx_n;
    s_frequencyBank[5] = (uint8_t)tx_k;
    s_frequencyBank[6] = (uint8_t)(tx_k >> 8);
    /* keep FSK_SWT as generated by RFPDK */
    s_frequencyBank[7] = (g_cmt2300aFrequencyBank[7] & CMT2300A_MASK_FSK_SWT)
                       | (band->vco_bank << 4)
                       | (uint8_t)(tx_k >> 16);

    s_txPower[0] = band->tx8 ? band->tx8 : g_cmt2300aTxBank[CMT2300A_CUS_TX8 - CMT2300A_TX_BANK_ADDR];
    s_txPower[1] = band->tx8 ? band->tx9 : g_cmt2300aTxBank[CMT2300A_CUS_TX9 - CMT2300A_TX_BANK_ADDR];
    return 0;
}

int RF_Init(void)
{
    uint8_t tmp;
    
    CMT2300A_InitGpio();
	CMT2300A_Init();
    
    /* Config registers */
    CMT2300A_ConfigRegBank(CMT2300A_CMT_BANK_ADDR       , g_cmt2300aCmtBank       , CMT2300A_CMT_BANK_SIZE       );
    CMT2300A_ConfigRegBank(CMT2300A_SYSTEM_BANK_ADDR    , g_cmt2300aSystemBank    , CMT2300A_SYSTEM_BANK_SIZE    );
    CMT2300A_ConfigRegBank(CMT2300A_FREQUENCY_BANK_ADDR , s_frequencyBank         , CMT2300A_FREQUENCY_BANK_SIZE );
    CMT2300A_ConfigRegBank(CMT2300A_DATA_RATE_BANK_ADDR , g_cmt2300aDataRateBank  , CMT2300A_DATA_RATE_BANK_SIZE );
    CMT2300A_ConfigRegBank(CMT2300A_BASEBAND_BANK_ADDR  , g_cmt2300aBasebandBank  , CMT2300A_BASEBAND_BANK_SIZE  );
    CMT2300A_ConfigRegBank(CMT2300A_TX_BANK_ADDR        , g_cmt2300aTxBank        , CMT2300A_TX_BANK_SIZE        );
    CMT2300A_WriteReg(CMT2300A_CUS_TX8, s_txPower[0]);
    CMT2300A_WriteReg(CMT2300A_CUS_TX9, s_txPower[1]);
    
    // xosc_aac_code[2:0] = 2
    tmp = (~0x07) & CMT2300A_ReadReg(CMT2300A_CUS_CMT10);
    CMT2300A_WriteReg(CMT2300A_CUS_CMT10, tmp|0x02);
    
	if(false==CMT2300A_IsExist()) 
	{
        //CMT2300A not found!
        return -1;
    }
    else
	{
        return 0;
    }
}

int StartTx() {
     if (RF_Init()!=0) {
        return 1;
	}
    CMT2300A_WriteReg(CMT2300A_CUS_SYS2,0); //???? 
    CMT2300A_ConfigGpio(CMT2300A_GPIO1_SEL_DOUT | CMT2300A_GPIO3_SEL_DIN | CMT2300A_GPIO2_SEL_INT2);
	CMT2300A_EnableTxDin(true);    
	CMT2300A_ConfigTxDin(CMT2300A_TX_DIN_SEL_GPIO1);
	CMT2300A_EnableTxDinInvert(false); 
	CMT2300A_GoSleep();
	CMT2300A_GoStby();
	if (CMT2300A_GoTx()) {
        return 0;
    } else {
        return 2;
    }
}
 

int StartRx() {
    if (RF_Init()!=0) {
        return 1;
	}

    CMT2300A_ConfigGpio (CMT2300A_GPIO1_SEL_INT1 | CMT2300A_GPIO2_SEL_INT2 | CMT2300A_GPIO3_SEL_DOUT);
	CMT2300A_ConfigInterrupt(CMT2300A_INT_SEL_TX_DONE, CMT2300A_INT_SEL_PKT_OK);
	CMT2300A_EnableInterrupt(CMT2300A_MASK_TX_DONE_EN | CMT2300A_MASK_PKT_DONE_EN);

	CMT2300A_WriteReg(CMT2300A_CUS_SYS2 , 0);

	CMT2300A_EnableFifoMerge(true);

	CMT2300A_WriteReg(CMT2300A_CUS_PKT29, 0x20); 

	CMT2300A_GoSleep();
	CMT2300A_GoStby();
	CMT2300A_ConfigGpio (CMT2300A_GPIO1_SEL_DCLK | CMT2300A_GPIO2_SEL_DOUT | CMT2300A_GPIO3_SEL_INT2);
	CMT2300A_ConfigInterrupt(CMT2300A_INT_SEL_SYNC_OK | CMT2300A_INT_SEL_SL_TMO, CMT2300A_INT_SEL_PKT_OK);
    CMT2300A_EnableFifoMerge(true);
	CMT2300A_ClearInterruptFlags();
	CMT2300A_ClearRxFifo();
	
    CMT2300A_GoRx();

	//CMT2300_IsExist()
	int rssi=CMT2300A_GetRssiDBm();
	//stream->print("rssi dbm ");
	//stream->println(rssi);

	CMT2300A_ClearInterruptFlags();
    return 0;
}